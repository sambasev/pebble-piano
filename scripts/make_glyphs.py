#!/usr/bin/env python3
"""Extract the SMuFL glyphs PianoPad draws from Bravura into Swift source.

Usage: python3 scripts/make_glyphs.py path/to/Bravura.otf > Sources/PianoGraderCore/Notation/Glyphs.swift
Needs fontTools (pip install fonttools). Bravura is © Steinberg Media Technologies GmbH,
SIL Open Font License 1.1 (see LICENSES/Bravura-OFL.txt).
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen

GLYPHS = [
    ("gClef", 0xE050), ("fClef", 0xE062),
    ("noteheadWhole", 0xE0A2), ("noteheadHalf", 0xE0A3), ("noteheadBlack", 0xE0A4),
    ("accidentalFlat", 0xE260), ("accidentalNatural", 0xE261), ("accidentalSharp", 0xE262),
    ("restWhole", 0xE4E3), ("restHalf", 0xE4E4), ("restQuarter", 0xE4E5), ("rest8th", 0xE4E6), ("rest16th", 0xE4E7),
    ("flag8thUp", 0xE240), ("flag8thDown", 0xE241), ("flag16thUp", 0xE242), ("flag16thDown", 0xE243),
    ("augmentationDot", 0xE1E7),
] + [(f"timeSig{d}", 0xE080 + d) for d in range(10)]

font = TTFont(sys.argv[1])
cmap = font.getBestCmap()
glyph_set = font.getGlyphSet()
units = font["head"].unitsPerEm

print("// Generated by scripts/make_glyphs.py from Bravura (SMuFL). Do not edit by hand.")
print("// Bravura © Steinberg Media Technologies GmbH, SIL Open Font License 1.1: see LICENSES/Bravura-OFL.txt.")
print()
print("/// Music symbols as outlines in staff spaces: x to the right, y up, origin on the glyph's")
print("/// SMuFL baseline (for a notehead, the line or space it sits on).")
print("public enum Glyph: String, CaseIterable, Sendable {")
for name, _ in GLYPHS:
    print(f"    case {name}")
print()
print("    /// Outline as SVG path data, in staff spaces with y up.")
print("    public var path: String {")
print("        switch self {")
scale = 4.0 / units  # SMuFL: one em is four staff spaces
for name, cp in GLYPHS:
    gname = cmap[cp]
    pen = SVGPathPen(glyph_set)
    glyph_set[gname].draw(pen)
    # Rescale every number in the path to staff spaces.
    import re
    def rescale(m):
        return f"{float(m.group(0)) * scale:.4g}"
    d = re.sub(r"-?\d+(?:\.\d+)?", rescale, pen.getCommands())
    print(f"        case .{name}: return \"{d}\"")
print("        }")
print("    }")
print()
print("    /// Bounding box in staff spaces: (minX, minY, maxX, maxY), y up.")
print("    public var bounds: (minX: Double, minY: Double, maxX: Double, maxY: Double) {")
print("        switch self {")
for name, cp in GLYPHS:
    bp = BoundsPen(glyph_set)
    glyph_set[cmap[cp]].draw(bp)
    x0, y0, x1, y1 = (v * scale for v in bp.bounds)
    print(f"        case .{name}: return ({x0:.4g}, {y0:.4g}, {x1:.4g}, {y1:.4g})")
print("        }")
print("    }")
print("}")
